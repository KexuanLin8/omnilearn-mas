function mermaidToTexSummary(code) {
  const lines = String(code)
    .replace(/```mermaid/i, "")
    .replace(/```/g, "")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => /-->|---|==>/.test(line))
    .map((line) => line
      .replace(/["\[\]]/g, "")
      .replace(/\s*-->|---|==>\s*/g, " $\\rightarrow$ ")
      .trim());
  if (!lines.length) return "\\paragraph{思维导图}图谱已在系统页面渲染。";
  return `\\paragraph{思维导图结构}\n\\begin{itemize}\n${lines.slice(0, 18).map((line) => `\\item ${texWithMath(line)}`).join("\n")}\n\\end{itemize}`;
}

function extractMermaidBlocks(markdown) {
  return Array.from(String(markdown || "").matchAll(/```([a-zA-Z]*)\s*\n([\s\S]*?)```/g))
    .map((match) => ({ lang: match[1].trim().toLowerCase(), code: match[2].trim() }))
    .filter(({ lang, code }) => lang === "mermaid" || /^(flowchart|graph|mindmap|sequenceDiagram|stateDiagram)\b/i.test(code))
    .map(({ code }) => code);
}

