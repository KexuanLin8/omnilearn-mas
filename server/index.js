function sanitizeMermaidCode(code) {
  const cleaned = String(code || "").trim();
  const hasInit = /^\s*(flowchart|graph|mindmap|sequenceDiagram|stateDiagram)\b/i.test(cleaned);
  const output = cleaned.split("\n").map((rawLine) => {
    const line = rawLine.trimEnd();
    if (!line.trim()) return "";
    if (/^\s*(flowchart|graph|mindmap|sequenceDiagram|stateDiagram|subgraph|end|classDef|class|style|linkStyle)\b/i.test(line)) return line;
    return line.replace(/\["([^"]*)"\]/g, (_match, label) => {
      const safe = String(label)
        .replace(/<[^>]+>/g, "")
        .replace(/\$+/g, "")
        .replace(/[`{}]/g, "")
        .replace(/\\/g, "")
        .replace(/\|/g, "/")
        .replace(/\*/g, "x")
        .replace(/"/g, "'")
        .slice(0, 52);
      return `["${safe}"]`;
    });
  }).join("\n");
  return hasInit ? output : `flowchart LR\n${output}`;
}

function escapeTex(text) {
  return String(text)
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([#$%&_{}])/g, "\\$1")
    .replace(/\^/g, "\\textasciicircum{}")
    .replace(/~/g, "\\textasciitilde{}");
}

function texWithMath(text) {
  const math = [];
  const masked = String(text).replace(/\$\$[\s\S]*?\$\$|\$[^$\n]+\$/g, (match) => {
    const token = `MATHPLACEHOLDER${math.length}`;
    math.push(match);
    return token;
  });
  let escaped = escapeTex(masked);
  math.forEach((value, index) => {
    escaped = escaped.replace(`MATHPLACEHOLDER${index}`, value);
  });
  return escaped;
}

function markdownToTex(markdown, turnIndex = 0, projectId = "") {
  const lines = normalizeMarkdownForTex(markdown).split("\n");
  const output = [];
  let listMode = null;
  let inCode = false;
  let codeIsMermaid = false;
  let codeBuffer = [];
  let mermaidIndex = 0;

  const closeList = () => {
    if (listMode) {
      output.push(listMode === "ol" ? "\\end{enumerate}" : "\\end{itemize}");
      listMode = null;
    }
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) {
      closeList();
      output.push("");
      continue;
    }
    if (line.startsWith("```")) {
      closeList();
      if (!inCode) {
        inCode = true;
        codeIsMermaid = line.toLowerCase().includes("mermaid");
        codeBuffer = [];
        if (line.toLowerCase().includes("mermaid")) {
          output.push("\\paragraph{思维导图}图谱已在系统页面渲染，下面保留结构摘要。");
        } else {
          output.push("\\paragraph{代码块}代码已在系统页面展示。");
        }
      } else {
        if (codeIsMermaid) {
          const imageName = imagePathForMermaid(turnIndex, mermaidIndex);
          if (projectId && existsSync(path.join(projectSessionDir(projectId), imageName))) {
            output.push(`\\begin{center}\\includegraphics[width=0.92\\textwidth,height=0.72\\textheight,keepaspectratio]{${escapeTex(imageName)}}\\end{center}`);
          } else {
            output.push(mermaidToTexSummary(codeBuffer.join("\n")));
          }
          mermaidIndex += 1;
        }
        if (!codeIsMermaid && /^(flowchart|graph|mindmap|sequenceDiagram|stateDiagram)\b/i.test(codeBuffer.join("\n").trim())) {
          const imageName = imagePathForMermaid(turnIndex, mermaidIndex);
          if (projectId && existsSync(path.join(projectSessionDir(projectId), imageName))) {
            output.push(`\\begin{center}\\includegraphics[width=0.92\\textwidth,height=0.72\\textheight,keepaspectratio]{${escapeTex(imageName)}}\\end{center}`);
          } else {
            output.push(mermaidToTexSummary(codeBuffer.join("\n")));
          }
          mermaidIndex += 1;
        }
        inCode = false;
        codeIsMermaid = false;
        codeBuffer = [];
      }
      continue;
    }
    if (inCode) {
      codeBuffer.push(line);
      continue;
    }
    if (/^#{1,3}\s+/.test(line)) {
      closeList();
      output.push(`\\section*{${escapeTex(line.replace(/^#{1,3}\s+/, ""))}}`);
      continue;
    }
    if (/^[-*]\s+/.test(line)) {
      if (listMode !== "ul") {
        closeList();
        output.push("\\begin{itemize}");
        listMode = "ul";
      }
      output.push(`\\item ${texWithMath(line.replace(/^[-*]\s+/, ""))}`);
      continue;
    }
    if (/^\d+\.\s+/.test(line)) {
      if (listMode !== "ol") {
        closeList();
        output.push("\\begin{enumerate}");
        listMode = "ol";
      }
      output.push(`\\item ${texWithMath(line.replace(/^\d+\.\s+/, ""))}`);
      continue;
    }
    closeList();
    output.push(`${texWithMath(line)}\n`);
  }
  closeList();
  return output.join("\n");
}

function sessionConversations(session) {
  if (Array.isArray(session.conversations)) return session.conversations;
  const legacyTurns = Array.isArray(session.turns) ? session.turns : [];
  const id = crypto.randomUUID();
  return legacyTurns.length ? [{
    id,
    title: "历史学习会话",
    archived: false,
    createdAt: session.startedAt || new Date().toISOString(),
    updatedAt: session.updatedAt || new Date().toISOString(),
    turns: legacyTurns.map((turn) => ({ ...turn, id: turn.id || crypto.randomUUID() })),
  }] : [];
}

function normalizeSession(session, projectId) {
  const conversations = sessionConversations(session).map((conversation) => ({
    ...conversation,
    id: conversation.id || crypto.randomUUID(),
    title: String(conversation.title || "未命名会话"),
    archived: Boolean(conversation.archived),
    turns: (conversation.turns || []).map((turn) => ({ ...turn, id: turn.id || crypto.randomUUID() })),
  }));
  const activeConversationId = conversations.some((item) => item.id === session.activeConversationId)
    ? session.activeConversationId
    : (conversations.find((item) => !item.archived)?.id || conversations[0]?.id || null);
  return { projectId, startedAt: session.startedAt || new Date().toISOString(), updatedAt: session.updatedAt, activeConversationId, conversations };
}

function selectedTurns(session, options = {}) {
  const conversations = sessionConversations(session);
  const conversationId = String(options.conversationId || "");
  const selectedIds = new Set(String(options.turnIds || "").split(",").filter(Boolean));
  const source = conversationId ? conversations.filter((item) => item.id === conversationId) : conversations;
  return source.flatMap((conversation) => conversation.turns || []).filter((turn) => !selectedIds.size || selectedIds.has(turn.id));
}

