async function renderMermaidImages(projectId, session) {
  const sessionDir = projectSessionDir(projectId);
  await fs.mkdir(sessionDir, { recursive: true });
  const mmdcCandidates = [
    process.env.MMDC_PATH,
    "/usr/local/bin/mmdc",
    "/usr/bin/mmdc",
    "mmdc",
  ].filter(Boolean);
  const mmdcExecutable = mmdcCandidates.find((candidate) => candidate === "mmdc" || existsSync(candidate)) || "mmdc";
  const chromiumCandidates = [
    process.env.CHROMIUM_PATH,
    "/snap/bin/chromium",
    "/usr/bin/chromium-browser",
    "/usr/bin/chromium",
    "/usr/bin/google-chrome",
  ].filter(Boolean);
  const chromiumExecutable = chromiumCandidates.find((candidate) => existsSync(candidate));
  const puppeteerConfigPath = path.join(sessionDir, "puppeteer-config.json");
  if (chromiumExecutable) {
    await fs.writeFile(puppeteerConfigPath, JSON.stringify({
      executablePath: chromiumExecutable,
      args: ["--no-sandbox", "--disable-setuid-sandbox", "--disable-dev-shm-usage"],
    }, null, 2), "utf8");
  }
  const renderArgs = (inputPath, outputPath) => [
    "-i", inputPath,
    "-o", outputPath,
    "-b", "transparent",
    "-s", "2",
    ...(chromiumExecutable ? ["-p", puppeteerConfigPath] : []),
  ];
  const errors = [];
  const turns = selectedTurns(session);
  for (let turnIndex = 0; turnIndex < turns.length; turnIndex += 1) {
    const blocks = extractMermaidBlocks(turns[turnIndex].answer);
    for (let blockIndex = 0; blockIndex < blocks.length; blockIndex += 1) {
      const inputPath = path.join(sessionDir, `mermaid-${turnIndex + 1}-${blockIndex + 1}.mmd`);
      const safeInputPath = path.join(sessionDir, `mermaid-${turnIndex + 1}-${blockIndex + 1}.safe.mmd`);
      const outputPath = path.join(sessionDir, imagePathForMermaid(turnIndex, blockIndex));
      await fs.unlink(outputPath).catch(() => undefined);
      await fs.writeFile(inputPath, blocks[blockIndex], "utf8");
      try {
        await execFileAsync(mmdcExecutable, renderArgs(inputPath, outputPath), { cwd: sessionDir, timeout: 90000 });
      } catch (error) {
        await fs.writeFile(safeInputPath, sanitizeMermaidCode(blocks[blockIndex]), "utf8");
        try {
          await execFileAsync(mmdcExecutable, renderArgs(safeInputPath, outputPath), { cwd: sessionDir, timeout: 90000 });
        } catch (safeError) {
          errors.push({
            turn: turnIndex + 1,
            block: blockIndex + 1,
            message: safeError.message,
            originalMessage: error.message,
            stderr: safeError.stderr || error.stderr || "",
          });
        }
      }
    }
  }
  if (errors.length) {
    await fs.writeFile(path.join(sessionDir, "mermaid-errors.json"), JSON.stringify(errors, null, 2), "utf8");
  }
}

async function appendSessionTurn(project, { question, answer, evidence, conversationId }) {
  const projectId = project.id;
  const session = await readSession(projectId);
  let conversation = session.conversations.find((item) => item.id === (conversationId || session.activeConversationId));
  if (!conversation) {
    conversation = { id: crypto.randomUUID(), title: "未命名会话", archived: false, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString(), turns: [] };
    session.conversations.push(conversation);
    session.activeConversationId = conversation.id;
  }
  session.updatedAt = new Date().toISOString();
  conversation.updatedAt = session.updatedAt;
  conversation.turns.push({
    id: crypto.randomUUID(),
    question,
    answer,
    evidence: evidence.map((item) => ({
      source: item.source,
      name: item.name || item.source,
      page: item.page || 1,
      chunkIndex: item.chunkIndex,
    })),
    createdAt: new Date().toISOString(),
  });
  await writeSession(projectId, session, project);
  return session;
}

function compileTex(projectId, texPath = projectSessionTexPath(projectId), outputName = "learning-session.pdf") {
  return new Promise((resolve, reject) => {
    const sessionDir = projectSessionDir(projectId);
    const inputTexPath = texPath;
    const localAppData = process.env.LOCALAPPDATA || "";
    const candidates = [
      process.env.XELATEX_PATH,
      path.join(localAppData, "Programs", "MiKTeX", "miktex", "bin", "x64", "xelatex.exe"),
      "xelatex",
    ].filter(Boolean);
    const executable = candidates.find((candidate) => candidate === "xelatex" || existsSync(candidate)) || "xelatex";
    execFile(executable, ["-interaction=nonstopmode", "-halt-on-error", "-file-line-error", "-output-directory", sessionDir, inputTexPath], { cwd: sessionDir }, (error, stdout, stderr) => {
      if (error) {
        const output = [stdout, stderr, error.message].filter(Boolean).join("\n");
        const lines = output.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
        const meaningful = lines.filter((line) =>
          /^!/.test(line)
          || /learning-session\.tex:\d+:/i.test(line)
          || /^l\.\d+/i.test(line)
          || /undefined control sequence|missing \$ inserted|extra },|runaway argument|emergency stop|fatal error/i.test(line)
        );
        error.texDetail = (meaningful.slice(0, 8).join(" ") || "XeLaTeX 未生成 PDF，请下载 TeX 检查具体内容。")
          .replace(/\s+/g, " ")
          .slice(0, 1200);
        error.message = output.slice(-12000);
        reject(error);
        return;
      }
      resolve(path.join(sessionDir, outputName));
    });
  });
}

