app.post("/api/auth/change-password", requireAuth, async (req, res) => {
  try {
    const currentPassword = String(req.body?.currentPassword || "");
    const newPassword = String(req.body?.newPassword || "");
    if (!(await passwordMatches(currentPassword, req.auth.user))) return res.status(400).json({ error: "当前密码不正确。" });
    if (newPassword.length < 8) return res.status(400).json({ error: "新密码至少需要 8 个字符。" });
    const secured = await passwordHash(newPassword);
    const users = await readAuthStore(usersPath);
    const nextUsers = users.map((user) => user.id === req.auth.user.id ? { ...user, passwordSalt: secured.salt, passwordHash: secured.hash } : user);
    await writeAuthStore(usersPath, nextUsers);
    const sessions = await readAuthStore(sessionsPath);
    await writeAuthStore(sessionsPath, sessions.filter((session) => session.userId !== req.auth.user.id || session.token === req.auth.token));
    res.json({ ok: true });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

