function publicMembership(user) {
  const quotaTokens = Number(user.quotaTokens || 0);
  const usedTokens = Number(user.usedTokens || 0);
  return {
    active: Boolean(user.membershipCodeId) && user.membershipStatus !== "disabled",
    quotaTokens,
    usedTokens,
    remainingTokens: Math.max(0, quotaTokens - usedTokens),
    redeemedAt: user.membershipRedeemedAt || null,
  };
}

