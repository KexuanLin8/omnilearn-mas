function estimatePage(index, chunk) {
  if (chunk.page) return chunk.page;
  const file = index.files?.find((item) => item.source === chunk.source);
  if (!file?.pages || !file?.chunks) return 1;
  const ratio = file.chunks <= 1 ? 0 : chunk.chunkIndex / Math.max(1, file.chunks - 1);
  return Math.max(1, Math.min(file.pages, Math.round(ratio * (file.pages - 1)) + 1));
}

function retrieve(index, query, limit = 8) {
  const queryTokens = tokenize(query);
  const scored = index.chunks
    .map((chunk) => {
      const tokenSet = new Set(chunk.tokens);
      const hits = queryTokens.filter((token) => tokenSet.has(token));
      const fuzzy = queryTokens.filter((token) => chunk.text.toLowerCase().includes(token)).length;
      const file = index.files.find((item) => item.source === chunk.source);
      return { ...chunk, name: file?.name || chunk.source, page: chunk.page || estimatePage(index, chunk), score: hits.length * 3 + fuzzy };
    })
    .filter((chunk) => chunk.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
  const fallback = index.chunks.slice(0, limit).map((chunk) => {
    const file = index.files.find((item) => item.source === chunk.source);
    return { ...chunk, name: file?.name || chunk.source, page: chunk.page || estimatePage(index, chunk), score: 0 };
  });
  return scored.length ? scored : fallback;
}

