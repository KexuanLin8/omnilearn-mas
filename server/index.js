function createMembershipCode() {
  const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
  const bytes = crypto.randomBytes(12);
  const raw = Array.from(bytes, (byte) => alphabet[byte % alphabet.length]).join("");
  return `SA-${raw.slice(0, 4)}-${raw.slice(4, 8)}-${raw.slice(8, 12)}`;
}

function estimateTokens(text) {
  const value = String(text || "");
  const chinese = (value.match(/[\u3400-\u9fff]/g) || []).length;
  const other = value.length - chinese;
  return Math.max(1, Math.ceil(chinese / 1.5 + other / 4));
}

async function assertTokenQuota(userId, estimatedTokens = 1) {
  const users = await readAuthStore(usersPath);
  const user = users.find((item) => item.id === userId);
  if (!user?.membershipCodeId || user.membershipStatus === "disabled") {
    const error = new Error("请先在账号设置中兑换会员码后使用 AI 功能。");
    error.statusCode = 402;
    throw error;
  }
  if (Number(user.quotaTokens || 0) - Number(user.usedTokens || 0) < estimatedTokens) {
    const error = new Error("会员 Token 额度不足，请联系管理员补充额度。");
    error.statusCode = 402;
    throw error;
  }
}

async function reserveTokenQuota(userId, maximumTokens) {
  const amount = Math.max(1, Math.ceil(Number(maximumTokens) || 1));
  return withAuthWrite(async () => {
    const users = await readAuthStore(usersPath);
    const user = users.find((item) => item.id === userId);
    if (!user?.membershipCodeId || user.membershipStatus === "disabled") {
      const error = new Error("请先在账号设置中兑换会员码后使用 AI 功能。");
      error.statusCode = 402;
      throw error;
    }
    const pending = [...tokenReservations.values()]
      .filter((item) => item.userId === userId)
      .reduce((sum, item) => sum + item.amount, 0);
    const available = Number(user.quotaTokens || 0) - Number(user.usedTokens || 0) - pending;
    if (available < amount) {
      const error = new Error("会员 Token 剩余额度不足以启动本次生成，请联系管理员补充额度。");
      error.statusCode = 402;
      throw error;
    }
    const id = crypto.randomUUID();
    tokenReservations.set(id, { userId, amount });
    return id;
  });
}

function releaseTokenReservation(reservationId) {
  if (reservationId) tokenReservations.delete(reservationId);
}

async function recordTokenUsage({ userId, projectId = null, action, model, prompt, output, usage, reservationId = null }) {
  const promptTokens = Number(usage?.prompt_tokens || usage?.promptTokens || estimateTokens(prompt));
  const completionTokens = Number(usage?.completion_tokens || usage?.completionTokens || estimateTokens(output));
  const totalTokens = Math.max(1, Number(usage?.total_tokens || usage?.totalTokens || promptTokens + completionTokens));
  await withAuthWrite(async () => {
    releaseTokenReservation(reservationId);
    const users = await readAuthStore(usersPath);
    const index = users.findIndex((item) => item.id === userId);
    if (index < 0) throw new Error("账号不存在。");
    const remaining = Number(users[index].quotaTokens || 0) - Number(users[index].usedTokens || 0);
    if (remaining < totalTokens) {
      const error = new Error("本次调用超过会员剩余额度，未记录该结果。请联系管理员补充额度。");
      error.statusCode = 402;
      throw error;
    }
    users[index] = { ...users[index], usedTokens: Number(users[index].usedTokens || 0) + totalTokens };
    await writeAuthStore(usersPath, users);
    const ledger = await readAuthStore(usageLedgerPath);
    ledger.push({ id: slugId(), userId, projectId, action, model, promptTokens, completionTokens, totalTokens, createdAt: new Date().toISOString() });
    await writeAuthStore(usageLedgerPath, ledger.slice(-100000));
  });
  return { promptTokens, completionTokens, totalTokens };
}

