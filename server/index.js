function mergeProfile(existing, inferred, survey = {}) {
  const source = new Map((existing?.dimensions || []).map((item) => [item.label, item]));
  const now = new Date().toISOString();
  const dimensions = inferred.map((item) => {
    const previous = source.get(item.label);
    const value = previous?.manual ? previous.value : item.value;
    return { label: item.label, value, score: profileScore(item.label, value), manual: Boolean(previous?.manual), updatedAt: now };
  });
  return { dimensions, survey: { ...(existing?.survey || {}), ...(survey || {}) }, updatedAt: now };
}

