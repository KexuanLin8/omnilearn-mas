app.post("/api/chat", async (req, res) => {
  const input = req.body || {};
  try {
    const project = await readOwnedProject(req, input.projectId);
    const index = await readIndex(project.id);
    const refinedQuestion = await refineQuestion(input, project, req.auth.user.id);
    const evidence = index?.chunks?.length ? retrieve(index, `${refinedQuestion}\n${input.message || ""}`, 5) : [];
    const prompt = buildAnswerPrompt(input, evidence, project, refinedQuestion);
    const model = resourceModel(input.resourceType, input.model);
    let usedSpark = Boolean(sparkConfig);
    let answer = "";
    try {
      if (sparkConfig) {
        const reservationId = await reserveTokenQuota(req.auth.user.id, maximumSparkTokens(prompt, model));
        let result;
        try {
          result = await callSparkWithFallback({ prompt, model });
          await recordTokenUsage({ userId: req.auth.user.id, projectId: project.id, action: input.resourceType ? `resource:${input.resourceType}` : "chat", model: result.model, prompt, output: result.text, usage: result.usage, reservationId });
        } catch (error) {
          releaseTokenReservation(reservationId);
          throw error;
        }
        answer = normalizeGeneratedMarkdown(result.text);
      } else {
        answer = normalizeGeneratedMarkdown(offlineGenerate(input, evidence, project));
      }
    } catch (error) {
      if (error.statusCode === 402) throw error;
      usedSpark = false;
      answer = normalizeGeneratedMarkdown(`${offlineGenerate(input, evidence, project)}\n\n> 星火调用未成功，当前使用本地检索兜底结果。错误：${error.message}`);
    }
    const previousProfile = await readProfile(project.id);
    const profile = mergeProfile(previousProfile, inferProfile(input), input.profileSurvey || {});
    const changes = profile.dimensions.filter((item) => {
      const before = previousProfile.dimensions?.find((entry) => entry.label === item.label);
      return !before || before.value !== item.value;
    }).map((item) => ({ label: item.label, value: item.value }));
    await writeProfile(project.id, profile);
    const session = await appendSessionTurn(project, { question: input.message || "", answer, evidence, conversationId: input.conversationId });
    const users = await readAuthStore(usersPath);
    const latestUser = users.find((item) => item.id === req.auth.user.id) || req.auth.user;
    res.json({ answer, evidence, profile: profile.dimensions, profileChanges: changes, usedSpark, agentTrace: agentTrace(input, usedSpark), sessionCount: selectedTurns(session).length, activeConversationId: session.activeConversationId, refinedQuestion, membership: publicMembership(latestUser) });
  } catch (error) {
    res.status(error.statusCode || 400).json({ error: error.message });
  }
});

