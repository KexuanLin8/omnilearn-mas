function buildMarkdownDocument(session, project, options = {}) {
  const turns = selectedTurns(session, options);
  const sections = turns.map((turn, index) => {
    const references = (turn.evidence || []).map((item, refIndex) => `- 引用 [${refIndex + 1}]：第 ${item.page || 1} 页 / 切片 ${(item.chunkIndex || 0) + 1}`).join("\n");
    return `## 问题 ${index + 1}\n\n### 学生问题\n${turn.question}\n\n### 系统解答\n${turn.answer}\n\n### 引用证据\n${references || "- 本轮未记录引用。"}`;
  });
  return `# ${project.course} 个性化学习记录\n\n${sections.join("\n\n---\n\n") || "暂无学习记录。"}\n`;
}

